// Curated, static detail content for the 50 tips seeded in
// supabase/migrations/20260828213000_expand_tips_catalog.sql. The Home card keeps the short
// public.tips.base_text; this catalog turns each seeded title into a short learning flow
// (v2): the five roles below, in order, for every one of the 50 titles.
//
//   basics   まずこれだけ
//   why      なぜ大事？
//   example  具体例                       (always a clearly hypothetical, educational scenario)
//   market   株価・相場とどう関係する？   (実践ではどう見る？ for the 10 advanced topics)
//   takeaway 覚えておくポイント
//
// Everything is evergreen: no current price/date, no claim about today's market, no buy/sell
// recommendation, no prediction, no real company or event. Numbers appear only inside examples
// that say they are hypothetical (仮の数字/仮の例). The learning content is static: no DB, RPC,
// API or AI is involved in rendering it.
//
// Keyed by the tip's title (its stable natural key in public.tips, not its uuid id, since the uuid
// can differ across environments/reseeds but the seeded title text is the one thing both this file
// and the DB agree on). An unknown title is a deliberate miss, not an error: the detail screen
// falls back to the RPC's own base_text rather than inventing content for a tip this catalog
// doesn't cover yet.
//
// This module has no RN imports so it can be tested with Deno and bundled by Metro.

export type TopicDetailRole = 'basics' | 'why' | 'example' | 'market' | 'takeaway';

/** The learning order, identical for every topic. */
export const TOPIC_DETAIL_ROLES: readonly TopicDetailRole[] = ['basics', 'why', 'example', 'market', 'takeaway'];

export const TOPIC_DETAIL_HEADINGS: Record<TopicDetailRole, string> = {
  basics: 'まずこれだけ',
  why: 'なぜ大事？',
  example: '具体例',
  market: '株価・相場とどう関係する？',
  takeaway: '覚えておくポイント',
};

/** The advanced (実践) topics read their market section as "how to look at it in practice". */
export const TOPIC_DETAIL_PRACTICAL_MARKET_HEADING = '実践ではどう見る？';

export type TopicDetailSection = {
  role: TopicDetailRole;
  heading: string;
  body: string;
};

export type TopicDetailEntry = {
  sections: TopicDetailSection[];
};

function build(marketHeading: string, basics: string, why: string, example: string, market: string, takeaway: string): TopicDetailEntry {
  return {
    sections: [
      { role: 'basics', heading: TOPIC_DETAIL_HEADINGS.basics, body: basics },
      { role: 'why', heading: TOPIC_DETAIL_HEADINGS.why, body: why },
      { role: 'example', heading: TOPIC_DETAIL_HEADINGS.example, body: example },
      { role: 'market', heading: marketHeading, body: market },
      { role: 'takeaway', heading: TOPIC_DETAIL_HEADINGS.takeaway, body: takeaway },
    ],
  };
}

// c = common (初級 / 中級), p = practical (実践)
const c = (basics: string, why: string, example: string, market: string, takeaway: string) =>
  build(TOPIC_DETAIL_HEADINGS.market, basics, why, example, market, takeaway);
const p = (basics: string, why: string, example: string, market: string, takeaway: string) =>
  build(TOPIC_DETAIL_PRACTICAL_MARKET_HEADING, basics, why, example, market, takeaway);

