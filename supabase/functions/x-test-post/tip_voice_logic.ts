export type TipDifficulty = "初級" | "中級" | "実践";

export const TIP_VOICE_RULES = [
  "小ネタです。株に詳しい人がXで一つだけ軽く教える感じにし、教科書・証券会社コラム・完成されたAI解説文にはしません。",
  "1投稿1ポイントです。定義、見方、補足、例外、まとめを一度に全部説明せず、そのテーマで一番伝えたい一つへ絞ってください。",
  "説明し切ることを目標にしません。短く自然なら少し余白を残して終えて構いません。",
  "例外、補足、注意点は、ないと意味を誤解する場合だけ入れます。毎回きれいに付け足しません。",
  "まとめ文を毎回付けず、結論を閉じすぎません。『〜すると分かりやすいです』『〜を見ると整理しやすいです』『〜まで見ると印象が変わります』『〜も確認したいところ』を定型の締めにしません。",
  "100〜220文字程度を基本目安にします。短く自然に成立するなら100文字未満でもよく、文字数や絵文字数を満たすために水増ししません。",
  "本人の実体験、保有、売買、利益、損失を作りません。『私は〜を見ています』のような架空の投資行動も書きません。",
  "絵文字は内容と会話の流れに合う範囲で自然に使ってください。",
] as const;

export function tipGenerationRules(difficulty: TipDifficulty): string[] {
  const difficultyRule = difficulty === "初級"
    ? "意味か基本的な見方のうち、そのテーマで一番大事な一つを自然な会話で伝えてください。"
    : difficulty === "中級"
    ? "理由、見る場所、注意点のうち、そのテーマで一番役立つ一つへ絞ってください。全部を順番に解説しません。"
    : "仕組み、実際の見方、注意場面のうち中心となる一つを具体的に伝え、情報を詰め込みすぎないでください。";
  return [
    "原則としてpostsは1件だけにしてください。",
    "全体は100〜220文字程度を基本目安にし、内容が成立するなら100文字未満も許可します。",
    difficultyRule,
  ];
}

export function tipVoiceEvaluationRules(postType: string): string[] {
  if (postType !== "tip") return [];
  return [
    "小ネタは1投稿1ポイントか、不要なまとめ・例外列挙で説明を完成させすぎていないかを評価してください。",
    "短く自然に成立していれば説明不足とは判定しません。文字数や絵文字数だけでpassedをfalseにしません。",
    "架空の実体験、保有、売買、利益、損失、本人の投資行動があればpassedをfalseにしてください。",
  ];
}
