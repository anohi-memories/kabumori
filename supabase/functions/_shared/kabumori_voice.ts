export function kabumoriImportantNewsVoice(variationKey: string): string[] {
  const seed = Array.from(variationKey).reduce(
    (total, character) => (total * 31 + (character.codePointAt(0) ?? 0)) >>> 0,
    0,
  );
  const openings = [
    "前置きなしで発表内容から入る",
    "企業名や対象を最初に置く",
    "市場への影響が分かる事実から入る",
    "短い速報見出しのあと自然な会話へ移る",
  ];
  const endings = [
    "影響を受けうる対象を一言添えて自然に終える",
    "条件や不確実性を一言だけ残す",
    "まとめを作らず、確認できた事実で終える",
    "日本株で見られそうな反応を断定せず添える",
  ];
  return [
    ...KABUMORI_VOICE,
    ...IMPORTANT_NEWS_VOICE,
    `今回の冒頭の方向性: ${openings[seed % openings.length]}`,
    `今回の締めの方向性: ${endings[(seed >>> 3) % endings.length]}`,
  ];
}
