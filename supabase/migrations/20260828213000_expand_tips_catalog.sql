update public.tips as existing
set difficulty = seed.difficulty,
    category = seed.category
from tips_seed as seed
where existing.title = seed.title;

insert into public.tips
  (title, difficulty, category, base_text, is_active)
select seed.title, seed.difficulty, seed.category, seed.base_text, true
from tips_seed as seed
where not exists (
  select 1 from public.tips existing where existing.title = seed.title
);

update public.tips
set difficulty = '初級'
where difficulty is null;

alter table public.tips alter column difficulty set not null;
