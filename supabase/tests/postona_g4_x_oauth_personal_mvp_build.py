#!/usr/bin/env python3
"""G4-02 #5 (Issue #561): derive G4's X OAuth for G5's PERSONAL MVP profile (g5pv) from the reviewed full-profile files.

Only two files change, and only in these places (each replacement must match exactly once, or the build refuses):
  001  the authority it requires: G5's MV + brand owner instead of F5's owner epoch (and the owner epoch must be ABSENT);
       the body of postona_g4_x_oauth.require_owner_epoch(text): the workspace owner's lifecycle_version (G5's g5pv
       generation), returned only while G5's MV says 'active' for exactly that generation
  005  the authority functions it requires to share the owner: the same swap
Everything else -- begin / complete / consume / disconnect bodies, tables, 002 / 003 / 004 and every rollback -- is used
verbatim, so their md5 pins (002 / 004 / 005 preconditions) keep holding. The column and the function keep the name
owner_epoch: in this profile they carry the g5pv generation.

Usage: postona_g4_x_oauth_personal_mvp_build.py <repo> [--check]   (--check: the committed outputs equal a fresh build)
"""
import sys
from pathlib import Path

SRC = "supabase/candidates/postona_g4_x_oauth_personal_epoch"
OUT = "supabase/candidates/postona_g4_x_oauth_personal_mvp"

BANNER = """-- GENERATED by supabase/tests/postona_g4_x_oauth_personal_mvp_build.py from {src} -- DO NOT EDIT BY HAND.
-- G4-02 #5 (Issue #561): G4's X OAuth on G5's PERSONAL MVP profile (G5-46 / G5-47: 1 person, 1 workspace, no brand owner
-- epoch). The only differences from the full-profile file are listed in the build script; the generation recorded at begin
-- and compared at complete / consume is G5's g5pv counter (the owner's common_accounts.lifecycle_version), checked by G5's
-- owner-only MV. Install exactly one profile. Rollback: the full-profile rollback files, verbatim.
"""

EPOCH_FN_OLD = """create function postona_g4_x_oauth.require_owner_epoch(p_brand_id text) returns bigint
language plpgsql volatile security definer set search_path = ''
as $$
declare v_epoch bigint;
begin
  v_epoch := private.account_lifecycle_brand_owner_epoch(p_brand_id);
  if v_epoch is null or v_epoch < 1 then
    raise exception 'OWNER_EPOCH_UNAVAILABLE';
  end if;
  return v_epoch;
end $$;
"""
EPOCH_FN_NEW = """-- PERSONAL MVP: the generation is G5's g5pv counter -- the workspace owner's lifecycle_version -- accepted only while G5's MV
-- answers 'active' for that very value (own derived workspace, S2-3 'own', service active, generation unchanged). The name
-- is kept so the reviewed begin / complete / consume bodies stay byte-identical; a moved generation between begin and the
-- callback is their OWNER_EPOCH_CHANGED.
create function postona_g4_x_oauth.require_owner_epoch(p_brand_id text) returns bigint
language plpgsql volatile security definer set search_path = ''
as $$
declare
  v_owner uuid;
  v_generation bigint;
  v_verdict text;
begin
  v_owner := private.account_lifecycle_brand_owner(p_brand_id);
  if v_owner is null then
    raise exception 'OWNER_EPOCH_UNAVAILABLE';
  end if;
  select a.lifecycle_version into v_generation from public.common_accounts a where a.user_id = v_owner;
  if v_generation is null or v_generation < 1 then
    raise exception 'OWNER_EPOCH_UNAVAILABLE';
  end if;
  v_verdict := private.postona_personal_worker_verdict(v_owner, p_brand_id, 'x_autopost', v_generation);
  if v_verdict is distinct from 'active' then
    raise exception '%', coalesce(v_verdict, 'OWNER_EPOCH_UNAVAILABLE');
  end if;
  return v_generation;
end $$;
"""

EDITS = {
    "001_x_oauth_personal_epoch.sql": ("001_x_oauth_g5pv.sql", [
        ("    ['private.account_lifecycle_brand_owner_epoch(text)', 'bigint']];\n",
         "    ['private.postona_personal_worker_verdict(uuid,text,text,bigint)', 'text'],\n"
         "    ['private.account_lifecycle_brand_owner(text)', 'uuid']];\n"),
        ("  if to_regnamespace('postona_g4_x_oauth') is not null then\n    raise exception 'G4X_ALREADY_APPLIED';\n  end if;\n",
         "  if to_regnamespace('postona_g4_x_oauth') is not null then\n    raise exception 'G4X_ALREADY_APPLIED';\n  end if;\n"
         "  -- PERSONAL MVP: F5's owner epoch must be absent (G5: the two profiles exclude each other)\n"
         "  if to_regprocedure('private.account_lifecycle_brand_owner_epoch(text)') is not null then\n"
         "    raise exception 'G4X_G5PV_PRECONDITION_FULL_PROFILE';\n  end if;\n"),
        (EPOCH_FN_OLD, EPOCH_FN_NEW),
    ]),
    "005_x_connect_lifecycle_t13.sql": ("005_x_connect_lifecycle_t13_g5pv.sql", [
        ("    'private.account_lifecycle_brand_owner_epoch(text)'::regprocedure] loop\n",
         "    'private.postona_personal_worker_verdict(uuid,text,text,bigint)'::regprocedure,\n"
         "    'private.account_lifecycle_brand_owner(text)'::regprocedure] loop\n"),
    ]),
}


def build(repo: Path) -> dict:
    out = {}
    for src_name, (dst_name, edits) in EDITS.items():
        text = (repo / SRC / src_name).read_text()
        for old, new in edits:
            n = text.count(old)
            if n != 1:
                raise SystemExit(f"{src_name}: expected exactly one match, found {n}: {old[:70]!r}")
            text = text.replace(old, new)
        if "account_lifecycle_brand_owner_epoch(" in text.replace("to_regprocedure('private.account_lifecycle_brand_owner_epoch(text)')", ""):
            # header comments may still name F5's function; no code may call it
            for line in text.splitlines():
                if "account_lifecycle_brand_owner_epoch(" in line and not line.lstrip().startswith("--") \
                        and "to_regprocedure('private.account_lifecycle_brand_owner_epoch(text)')" not in line:
                    raise SystemExit(f"{dst_name}: still calls the owner epoch: {line.strip()}")
        out[dst_name] = BANNER.format(src=f"{SRC}/{src_name}") + text
    return out


def main() -> None:
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    repo = Path(sys.argv[1])
    built = build(repo)
    if "--check" in sys.argv[2:]:
        for name, text in built.items():
            if (repo / OUT / name).read_text() != text:
                raise SystemExit(f"{OUT}/{name} does not re-derive")
        print("G4X_G5PV_BUILD_CHECK_OK")
        return
    (repo / OUT).mkdir(exist_ok=True)
    for name, text in built.items():
        (repo / OUT / name).write_text(text)
        print(f"wrote {OUT}/{name}")


if __name__ == "__main__":
    main()
