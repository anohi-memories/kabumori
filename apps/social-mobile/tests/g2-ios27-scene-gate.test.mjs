// G2 QA (Issue #317, task postona-g2-ios27-scene-native-launch-gate-qa-20261020) -- QA only, no product code.
// The iOS 27 launch blocker as a release gate on the app's OWN configuration (offline, static): with Expo SDK 57 the
// standard prebuild generates an AppDelegate that creates its own UIWindow and an Info.plist without
// UIApplicationSceneManifest, and an app linked with the iOS 27 SDK then traps at launch
// (_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption; evidence in G2 PR #348 and
// docs/postona/qa/g2-ios27-gate/). Nothing here builds or launches anything.
//
// "FINDING .." / "OBSERVATION .." pass while the gap exists and FAIL once the owner fixes it (then the owner replaces
// them with the acceptance runs listed in the README).
import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const appJson = JSON.parse(readFileSync(resolve(root, 'app.json'), 'utf8')).expo;
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const lock = JSON.parse(readFileSync(resolve(root, 'package-lock.json'), 'utf8'));
const lockedExpo = lock.packages['node_modules/expo']?.version ?? null;
const plugins = (appJson.plugins ?? []).map((p) => (Array.isArray(p) ? p[0] : p));
const localPlugins = plugins.filter((p) => typeof p === 'string' && (p.startsWith('./') || p.startsWith('../')));
const hasAppConfig = ['app.config.js', 'app.config.ts', 'app.config.mjs', 'app.config.cjs'].some((f) => existsSync(resolve(root, f)));

test('FINDING G2-IOS27 (release blocker, owner of the native config undecided): Expo SDK 57 with no scene adoption in the app config -- the standard prebuild cannot produce a scene-based app', () => {
  assert.match(lockedExpo ?? '', /^57\./u, 'the lockfile pins Expo SDK 57 (SDK 58 templates adopt scenes by themselves)');
  assert.equal(appJson.ios?.infoPlist?.UIApplicationSceneManifest, undefined, 'no UIApplicationSceneManifest in ios.infoPlist');
  assert.deepEqual(localPlugins, [], 'no local config plugin');
  assert.equal(hasAppConfig, false, 'no app.config.* that could add one');
  assert.equal(existsSync(resolve(root, 'plugins')), false, 'no plugins/ directory');
  assert.equal(existsSync(resolve(root, 'ios')), false, 'no committed ios/ (the native project is generated by prebuild)');
});

test('G2 check: the installed Expo already ships what a scene adoption needs (ExpoAppSceneDelegate, ExpoReactNativeFactoryProvider) -- no new dependency for a config-plugin fix', () => {
  const expoDir = resolve(root, 'node_modules/expo');
  const installed = JSON.parse(readFileSync(resolve(expoDir, 'package.json'), 'utf8')).version;
  assert.equal(installed, lockedExpo, 'the installed Expo is the locked one');
  const delegates = readdirSync(resolve(expoDir, 'ios/AppDelegates'));
  for (const file of ['ExpoAppSceneDelegate.swift', 'ExpoReactNativeFactoryProvider.swift', 'ExpoAppDelegate.swift']) assert.ok(delegates.includes(file), file);
  const scene = readFileSync(resolve(expoDir, 'ios/AppDelegates/ExpoAppSceneDelegate.swift'), 'utf8');
  assert.match(scene, /class ExpoAppSceneDelegate/u);
});

test('OBSERVATION G2-IOS27-B (owner of the native config): the standard prebuild rewrites tracked files -- no ios.bundleIdentifier in app.json, and the "ios" script is "expo start --ios" -- so a clean build dirties the tree', () => {
  assert.equal(appJson.ios?.bundleIdentifier, undefined, 'prebuild writes com.anohi-memories.kabumori-social-mobile into app.json');
  assert.equal(pkg.scripts?.ios, 'expo start --ios', 'prebuild rewrites it to "expo run:ios"');
});

// ---- negative control: each of the three fixes makes the FINDING's condition false ----------------------------------

/** The FINDING's condition, over a given configuration (the real one is checked above). */
function sceneGap({ expo, infoPlistScene, plugins: list, appConfig }) {
  const local = list.filter((p) => typeof p === 'string' && (p.startsWith('./') || p.startsWith('../')));
  return /^57\./u.test(expo) && infoPlistScene === undefined && local.length === 0 && !appConfig;
}

test('negative control: the gap condition is true for today\'s config and false for each fix (infoPlist key + AppDelegate change via a local plugin, an app.config, or SDK 58)', () => {
  const today = { expo: lockedExpo, infoPlistScene: appJson.ios?.infoPlist?.UIApplicationSceneManifest, plugins, appConfig: hasAppConfig };
  assert.equal(sceneGap(today), true);
  assert.equal(sceneGap({ ...today, plugins: [...plugins, './plugins/with-ios27-scene'] }), false, 'a local config plugin');
  assert.equal(sceneGap({ ...today, appConfig: true }), false, 'an app.config.* that adds it');
  assert.equal(sceneGap({ ...today, infoPlistScene: { UIApplicationSupportsMultipleScenes: false } }), false, 'the infoPlist key (the AppDelegate still has to change too)');
  assert.equal(sceneGap({ ...today, expo: '58.0.16' }), false, 'SDK 58');
});
