#!/usr/bin/env python3
"""J1-b: builds a self-contained SQL file that installs the REAL current definitions of the news feed RPC chain
(extracted verbatim from the repository migrations) on top of a minimal stub schema, for offline proof on a throwaway
local Postgres. Reads migrations only; writes nothing outside the given output path. No production access."""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[3] / "supabase" / "migrations"

def read(name: str) -> str:
    return (root / name).read_text()

def extract_function(text: str, signature_re: str) -> str:
    m = re.search(signature_re, text)
    if not m:
        raise SystemExit(f"function not found: {signature_re}")
    end = text.index("\n$$;", m.start()) + len("\n$$;")
    return text[m.start():end]

M1 = "20260911090000_app_severity_news_feed.sql"
M2 = "20260911120000_market_relevance_news_feed.sql"
M3 = "20260911200000_market_critical_alerts_dedupe.sql"
M4 = "20260913140000_broad_news_visibility_notification_presets.sql"
M5 = "20260917120000_broad_news_phase5_all_useful_scope_and_run_diagnostics.sql"

parts = []
parts.append("-- generated by build_rpc_sql.py from the repository migrations; do not edit")
parts.append(extract_function(read(M1), r"create or replace function public\.important_news_ir_subtype\("))
parts.append(extract_function(read(M1), r"create or replace function public\.important_news_app_severity\("))
parts.append(extract_function(read(M2), r"create or replace function public\.important_news_market_themes\("))
parts.append(extract_function(read(M2), r"create or replace function public\.important_news_theme_sectors\("))
parts.append(extract_function(read(M3), r"create or replace function public\.important_news_number_signature\("))
parts.append(extract_function(read(M3), r"create or replace function public\.important_news_same_event\("))
base = extract_function(read(M4), r"create function public\.get_my_important_stock_news\(")
parts.append(base)
parts.append("alter function public.get_my_important_stock_news(integer) rename to get_my_important_stock_news_phase5_base;")
parts.append(extract_function(read(M5), r"create function public\.get_my_important_stock_news\("))
# privileges exactly as the production migration sets them (so the ACL comparison with a candidate is meaningful)
m5 = read(M5)
for stmt in (
    "revoke all on function public.get_my_important_stock_news_phase5_base(integer)\n  from public, anon, authenticated, service_role;",
    "revoke all on function public.get_my_important_stock_news(integer)\n  from public, anon, authenticated, service_role;",
    "grant execute on function public.get_my_important_stock_news(integer) to authenticated;",
):
    if stmt not in m5:
        raise SystemExit(f"privilege statement not found in migration: {stmt[:60]!r}")
    parts.append(stmt)
pathlib.Path(sys.argv[1]).write_text("\n\n".join(parts) + "\n")
print("wrote", sys.argv[1])
